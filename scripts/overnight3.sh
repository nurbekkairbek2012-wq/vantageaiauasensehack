#!/usr/bin/env bash
# Переобучение на всех скачанных архивах AerialWaste.
#
# Первый прогон использовал один архив: 1740 снимков, 558 свалок,
# ROC-AUC 0,836, перенос 0,786 при интервале 0,571–0,968. Интервал широкий
# из-за трёх положительных примеров на нашей стороне — этого больше данных
# в обучении не исправят. Но качество самой модели они поднять могут, а с
# ним и верхнюю часть списка, где сейчас два склада получают 0,99.
cd "$(dirname "$0")/.." || exit 1
PY=".venv/Scripts/python.exe"
say() { echo "[$(date +%H:%M:%S)] $*" | tee -a overnight.log; }

say "═══ цепочка 3: переобучение на тройном объёме ═══"

for n in 1 2; do
  say "жду архив images$n.zip"
  bash scripts/wait_stable.sh "data/aerialwaste/images$n.zip" 90 150
done

for n in 0 1 2; do
  SZ=$(stat -c%s "data/aerialwaste/images$n.zip" 2>/dev/null || echo 0)
  say "images$n.zip: $((SZ/1048576)) МБ"
done

# Кэш эмбеддингов считается по одному архиву и новых снимков не увидит.
# Убираем его явно, а не молча: пропущенный шаг здесь не падает, он просто
# оставляет вчерашнюю модель, и заметить это нечем.
say "сбрасываю кэш эмбеддингов"
rm -f data/aerialwaste/embeddings.npz

say "эмбеддинги и обучение (долго: снимков втрое больше)"
"$PY" scripts/train_aerialwaste.py >> aerialwaste.log 2>&1 && say "обучение готово" || say "ОБУЧЕНИЕ УПАЛО"

say "перепроверка переноса"
"$PY" scripts/eval_on_ours.py >> aerialwaste.log 2>&1 && say "проверка готова" || say "ПРОВЕРКА УПАЛА"

say "═══ цепочка 3 закончена ═══"
