"""Имя файла в кэше снимков высокого разрешения.

── Почему не по номеру объекта ─────────────────────────────────────────

Кэш звался по номеру кандидата: ``C00317_z17.png``. Номер сквозной внутри
области, но НЕ между областями — ровно та причина, по которой слияние
приписывает к номерам приставку города.

В ночь на 23 августа это выстрелило. Северное кольцо и западная промзона
обе содержат C00317, и объекты эти лежат в 24 км друг от друга. Снимок
северного кольца, скачанный в 03:36, был показан вместо снимка промзоны в
04:50 — и на контактном листе я принял его за настоящую свалку, потому что
северный C00317 настоящей свалкой и является.

Пять снимков из сорока одного оказались чужими. Ошибка не давала о себе
знать ничем: файл на месте, картинка открывается, местность правдоподобная.

── Почему по координатам ───────────────────────────────────────────────

Снимок показывает МЕСТО. Место и должно быть ключом: оно не меняется при
пересчёте, не зависит от нумерации и одинаково у любых двух прогонов,
накрывших одну точку — то есть кэш продолжает работать между областями,
а не ломается.

Пять знаков после запятой — примерно метр на широте Астаны. Это мельче
пикселя снимка (0,5 м на пиксель при окне в 450 м), так что два разных
объекта в одну клетку не попадут, а один и тот же при пересчёте попадёт.

── Старые файлы ────────────────────────────────────────────────────────

Файлы старого вида остаются лежать: удалять их незачем, они просто больше
не читаются. Место в репозиторий не уезжает — data/highres в .gitignore.
"""


def cache_name(lat: float, lon: float, zoom: int) -> str:
    """Имя файла снимка для точки и зума."""
    return f"{lat:.5f}_{lon:.5f}_z{zoom}.png"
