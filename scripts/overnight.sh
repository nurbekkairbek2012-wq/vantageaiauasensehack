#!/usr/bin/env bash
# Ночная цепочка: считает сама, не дожидаясь ничьих команд.
#
# Каждый шаг пишет в overnight.log с отметкой времени. Упавший шаг не
# останавливает цепочку — утром важнее иметь четыре результата из пяти,
# чем один и остановку в три часа ночи.

cd "$(dirname "$0")/.." || exit 1
PY=".venv/Scripts/python.exe"
LOG="overnight.log"

say() { echo "[$(date +%H:%M:%S)] $*" | tee -a "$LOG"; }

say "═══ ночная цепочка запущена ═══"

# ── 1. Дождаться первого досчёта ────────────────────────────────────────
say "1/5 жду окончания finish_all"
while ! grep -aq "Сводка" finish_all.log 2>/dev/null; do sleep 30; done
say "1/5 досчёт закончен"

# ── 2. Пересчитать прогноз новым кодом ──────────────────────────────────
# Первый досчёт импортировал risk.py до правки и опубликовал старые
# квартили. Признаки уже в кеше, поэтому повтор быстрый.
say "2/5 пересчёт прогноза новым кодом (верхние 5%, а не квартили)"
"$PY" scripts/finish_all.py --no-signals --no-verify >> finish_all2.log 2>&1
say "2/5 готово"

# ── 3. Дождаться архива AerialWaste ─────────────────────────────────────
say "3/5 жду архив AerialWaste"
for _ in $(seq 1 480); do
  # curl дописывает файл; окончанием считаем момент, когда процесс ушёл
  pgrep -f "images0.zip" > /dev/null 2>&1 || break
  sleep 30
done
SIZE=$(stat -c%s data/aerialwaste/images0.zip 2>/dev/null || echo 0)
say "3/5 архив: $((SIZE/1048576)) МБ"

if [ "$SIZE" -lt 500000000 ]; then
  say "3/5 архив недокачан — обучение пропускаю"
else
  # ── 4. Эмбеддинги и обучение ──────────────────────────────────────────
  say "4/5 эмбеддинги и обучение на AerialWaste (это долго)"
  "$PY" scripts/train_aerialwaste.py >> aerialwaste.log 2>&1
  say "4/5 готово"

  # ── 5. Честная проверка переноса на наши метки ────────────────────────
  say "5/5 проверка переноса на казахстанских метках"
  "$PY" scripts/eval_on_ours.py >> aerialwaste.log 2>&1
  say "5/5 готово"
fi

say "═══ цепочка закончена ═══"
