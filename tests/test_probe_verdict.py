"""Вердикт замера области обязан согласовываться с прогонами, которые уже были.

Порог «запускать / не запускать» — это не настройка вкуса. За ним стоят
четыре прогона с известным исходом, каждый по несколько часов счёта и по
часу просмотра глазами:

    север        94,7 контура на км²   3 подтверждённых + 5 опознанных свалок
    юго-восток   18,1                  0 настоящих из 9 просмотренных
    восток        6,8                  0 настоящих из 33

Если правка порогов начнёт пропускать восточный пояс, это значит, что
замер снова разрешает потратить четыре часа на область, про которую уже
известно, что она пуста. Тест держит вердикт привязанным к тому, что
измерено, а не к тому, что кажется разумным.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from probe_city import verdict  # noqa: E402


#: Замеренные области: (имя, годной земли, промышленной, контуров на км²).
MEASURED = {
    "север": (0.322, 0.0302, 94.7),
    "запад · промзона": (0.181, 0.0208, 97.8),
    "юго-восток": (0.245, 0.0006, 18.1),
    "восток": (0.233, 0.0000, 6.8),
}


class TestVerdictMatchesWhatWasMeasured:
    @pytest.mark.parametrize("name", ["восток", "юго-восток"])
    def test_areas_that_gave_zero_landfills_are_refused(self, name):
        """Пояса, давшие ноль настоящих свалок из 42 находок, — «не запускать».

        Обе области проходили по «годной земле» с запасом (23,3% и 24,5%),
        и именно поэтому были запущены. Отсеять их мог только замер
        полноты карты.
        """
        assert "НЕ ЗАПУСКАТЬ" in verdict(*MEASURED[name])

    @pytest.mark.parametrize("name", ["север", "запад · промзона"])
    def test_areas_where_the_method_works_are_allowed(self, name):
        """Область, давшая восемь свалок, не должна отсеиваться.

        Порог, отсекающий восточный пояс, легко поставить так, что он
        заодно отсечёт и работающую промзону — у неё годной земли
        меньше всех (18,1%).
        """
        answer = verdict(*MEASURED[name])
        assert "НЕ ЗАПУСКАТЬ" not in answer
        assert "неизвестно" not in answer

    def test_untested_middle_is_called_untested(self):
        """Между 18 и 95 прогонов не было — и вердикт обязан это сказать.

        Западный пояс сёл (32,5) лежит ровно в этой середине. Назвать его
        «хорошей областью» значило бы выдать догадку за замер.
        """
        assert "неизвестно" in verdict(0.207, 0.0062, 32.5)

    def test_density_outranks_good_land(self):
        """Полнота карты решает раньше площади годной земли.

        Восточный пояс имел лучшую годную землю из провалившихся (23,3%)
        и был запущен именно поэтому. Порядок проверок должен быть таким,
        чтобы это больше не повторилось.
        """
        assert "НЕ ЗАПУСКАТЬ" in verdict(0.90, 0.05, 6.8)

    def test_missing_density_still_answers(self):
        """Overpass может не ответить — замер обязан деградировать, а не падать."""
        assert verdict(0.322, 0.0302, None)
        assert verdict(0.322, None, None)
