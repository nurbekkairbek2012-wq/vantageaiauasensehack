"""Порядок просмотра находок: сначала те, что похожи на свалку по смыслу.

── Что это и чего это НЕ делает ────────────────────────────────────────

Подсказка порядка, а не фильтр. Ни одна находка не снимается: меняется
только очередь, в которой человек смотрит снимки. Цена ошибки поэтому
нулевая — в худшем случае свалка окажется ниже в списке, но не исчезнет.

── На чём держится ─────────────────────────────────────────────────────

Два признака, которые на экзамене (scripts/check_triage.py) ведут себя
как признаки КЛАССА, а не места:

  * удалённость от проезжей дороги — свалку ссыпают в стороне от
    проезда, склад и площадка стоят у дороги;
  * число кусков пятна — ссыпка рваная, площадка и крыша одним куском.

Каждый переводится в ранг внутри своей очереди (процентиль), и берётся
среднее. Без обучения: подгонять под семь свалок нечего.

── Что измерено (27 сентября, северное кольцо, 51 объект, 7 свалок) ────

  порядок                        ROC-AUC   90% интервал   последняя свалка
  снимок + дорога + куски         0,87      0,79 – 0,95    14-я из 51
  дорога + куски                  0,77      0,63 – 0,90    31-я из 51
  случайный                       0,50                     около 45-й

Снимок оценивает DINOv2, обученная на дроновом наборе незаконных свалок
(CC-BY-4.0), казахстанском наборе OSM и на отказах человека из ДРУГИХ
поясов (models/dinov2_chip_open.joblib) — ни одного объекта северного
кольца в обучении и ни одного снимка AerialWaste (CC BY-NC-ND). Это та
же оценка, что на карточке объекта (highres_score, scripts/attach_chipmodel.py):
окно 190 м по центру объекта, среднее по восьми поворотам и отражениям.

Оговорка: эти два признака выбраны на тех же данных, поэтому оценка
оптимистична. Подтвердит или опровергнет её первая новая территория.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

#: Признаки подсказки и направление: больше — выше в очереди.
FEATURES = ("dist_road_m", "n_pieces")


#: Оценка снимка моделью DINOv2 (scripts/attach_chipmodel.py). Если она есть,
#: подсказка = (ранг снимка + 2 × ранг «дорога + куски») / 3.
IMAGE = "highres_score"


def review_priority(frame: pd.DataFrame) -> pd.Series:
    """Оценка 0..1: среднее процентилей признаков внутри очереди.

    Пропуски признака получают середину (0,5): отсутствие данных не
    должно ни поднимать, ни топить объект.

    Если у очереди есть оценка снимка (highres_score), она добавляется с
    весом 1 к 2. На экзамене северного кольца так все семь свалок попали в
    первые 14 из 51 объекта: ROC-AUC 0,87 (90%: 0,79–0,95) против 0,77 у
    «дорога + куски» и ~45 объектов при случайном порядке.
    """
    parts = []
    for column in FEATURES:
        if column not in frame:
            continue
        values = pd.to_numeric(frame[column], errors="coerce")
        parts.append(values.rank(pct=True).fillna(0.5))
    if not parts:
        base = pd.Series(np.full(len(frame), 0.5), index=frame.index)
    else:
        base = sum(parts) / len(parts)
    if IMAGE in frame and pd.to_numeric(frame[IMAGE], errors="coerce").notna().any():
        image = pd.to_numeric(frame[IMAGE], errors="coerce").rank(pct=True).fillna(0.5)
        return (image + 2 * base) / 3
    return base


def review_order(frame: pd.DataFrame) -> pd.DataFrame:
    """Очередь просмотра: по подсказке, при равенстве — крупные раньше."""
    out = frame.copy()
    out["review_priority"] = review_priority(out).round(3)
    keys = ["review_priority"] + (["area_m2"] if "area_m2" in out else [])
    return out.sort_values(keys, ascending=False)


__all__ = ["FEATURES", "IMAGE", "review_order", "review_priority"]
