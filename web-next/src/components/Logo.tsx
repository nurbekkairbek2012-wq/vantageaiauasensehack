/* Знак Vantage.
 *
 * Знак нарисован заказчиком; здесь он переведён в SVG. Растр не годился по
 * трём причинам, и каждая всплыла бы в первый же день: он не масштабируется
 * (в шапке 26 px, на лендинге 40, на печати больше), он нарисован тёмным по
 * белому, а сайт тёмный, и цвета в нём зашиты намертво — при смене палитры
 * знак остался бы от прежней.
 *
 * ── Что в знаке ────────────────────────────────────────────────────────
 *
 * V — контуром, а не заливкой. Орбита — эллипс, наклонённый и проходящий
 * позади буквы. Метка на месте нижней вершины V: точка на карте ровно там,
 * куда буква указывает остриём.
 *
 * ── Тёмный фон ─────────────────────────────────────────────────────────
 *
 * Исходник тёмно-фиолетовый по белому. Простая инверсия здесь не годится:
 * орбита в оригинале — единственный яркий элемент, и после инверсии яркой
 * стала бы буква, а орбита ушла бы в фон. Поэтому роли сохранены, а не
 * цвета: буква и метка светлые (они несут форму), орбита остаётся
 * фиолетовой (она несёт цвет марки).
 *
 * Метка — единственное место, где пришлось отойти от исходника. Там она
 * того же тёмного цвета, что и буква, и читается потому, что лежит на белой
 * заливке внутри V. На тёмном фоне заливки нет, и светлая метка внутри
 * светлого контура тонула — снимок в четырёхкратном увеличении показал
 * каплю без формы. Метка взяла цвет орбиты: это ровно то, что продукт
 * находит, и выделить её честнее, чем сохранить оттенок.
 *
 * ── Почему отрисовки две ───────────────────────────────────────────────
 *
 * Ниже 26 px контурная V превращается в размытую полосу: два параллельных
 * штриха в полпикселя сливаются. Орбита на таком размере — серая дуга,
 * метка — точка. Поэтому на мелких размерах V сплошная, орбиты нет, метка
 * укрупнена. Это не другой знак, а тот же силуэт, сведённый к тому, что на
 * такой высоте вообще различимо.
 */

type Props = { size?: number; className?: string };

/* Ниже этого размера контур и орбита превращаются в грязь. Порог поднят с
   26 до 32 по снимку шапки: на тридцати пикселях обводка буквы и орбита
   дают по девять десятых физического пикселя каждая, сливаются в серое, и
   знак читается как клякса. Проверять такое на глаз в браузере бесполезно —
   нужен снимок в натуральную величину. */
const DETAIL_FROM = 32;

/* Геометрия в системе 64×64, снятая с присланного знака.
 *
 * Пропорции пришлось мерить, а не прикидывать: с первого раза V вышла
 * узкой и крутой, орбита — тесной, и знак перестал быть похож на себя.
 * В исходнике V шире, чем выше (250 к 215), орбита заметно шире буквы
 * (360 против 250) и наклонена примерно на 20°, а остриё метки уходит
 * ниже вершины буквы.
 *
 * Буква стоит левее центра, а орбита — правее: это не погрешность, так
 * в исходнике. Смещение и создаёт ощущение, что кольцо облетает букву,
 * а не надето на неё.
 */
const V_OUTLINE = 'M8 14 L19 14 L28.2 40.5 L38.5 14 L49.5 14 L28.2 51 Z';

/** Сплошная V для мелких размеров: тот же силуэт без внутреннего выреза. */
const V_SOLID = 'M9 15 L20 15 L28.2 39 L37.5 15 L48.5 15 L28.2 50 Z';

export function Mark({ size = 32, className = '' }: Props) {
  const detailed = size >= DETAIL_FROM;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 64 64"
      fill="none"
      className={className}
      aria-hidden="true"
    >
      {detailed ? (
        <>
          {/* Орбита проходит позади буквы: она облетает V, а не лежит на
              ней. Разрыв делается не вторым эллипсом, а порядком отрисовки —
              буква с толстой обводкой цвета подложки перекрывает дугу там,
              где та должна уходить за неё. */}
          <ellipse
            cx="32"
            cy="29"
            rx="30"
            ry="15.5"
            transform="rotate(-20 32 29)"
            stroke="var(--color-violet-lit)"
            strokeWidth="1.9"
            fill="none"
          />

          {/* Обводка цветом подложки — та самая «дырка» под орбитой. */}
          <path d={V_OUTLINE} stroke="var(--color-soot)" strokeWidth="3.4" strokeLinejoin="miter" fill="none" />
          <path d={V_OUTLINE} stroke="var(--color-line)" strokeWidth="1.7" strokeLinejoin="miter" fill="none" />

          {/* Метка на месте нижней вершины: точка на карте ровно там, куда
              буква указывает остриём. */}
          <path
            d="M28.2 36.4a5.7 5.7 0 0 0-5.7 5.7c0 4.2 4.6 9 5.4 9.8.2.2.4.2.6 0 .8-.8 5.4-5.6 5.4-9.8a5.7 5.7 0 0 0-5.7-5.7z"
            fill="var(--color-violet-lit)"
            stroke="var(--color-soot)"
            strokeWidth="1.1"
          />
          <circle cx="28.2" cy="42.1" r="2.1" fill="var(--color-soot)" />
        </>
      ) : (
        <>
          <path d={V_SOLID} fill="var(--color-line)" />
          <path
            d="M28.2 34.5a7 7 0 0 0-7 7c0 5.2 5.7 11 6.7 12 .2.2.4.2.6 0 1-1 6.7-6.8 6.7-12a7 7 0 0 0-7-7z"
            fill="var(--color-violet-lit)"
          />
          <circle cx="28.2" cy="41.5" r="2.6" fill="var(--color-soot)" />
        </>
      )}
    </svg>
  );
}

export function Logo({ size = 30, className = '' }: Props) {
  return (
    <span className={`inline-flex items-center gap-2.5 ${className}`}>
      {/* Знак крупнее кегля слова: в связке он несёт форму, а слово —
          чтение. При равной высоте знак выглядит приставкой к тексту. */}
      <Mark size={size * 1.35} />
      {/* «AI» — суффикс, а не часть слова, и набран он иначе: другим
          цветом и меньшим кеглем. Набранный в одну строку одинаково,
          «Vantage AI» читается как двусложное имя, и ударение уезжает на
          суффикс — тогда как имя продукта остаётся первым словом.

          Без uppercase у основного слова: капслок с разрядкой читается как
          аббревиатура, у такого слова нет силуэта. В самом знаке надпись
          капслоком, но там она часть рисунка. */}
      <span className="inline-flex items-baseline gap-[0.26em]">
        <span
          className="font-display font-semibold leading-none text-line"
          style={{ fontSize: size * 0.82, letterSpacing: '0.01em' }}
        >
          Vantage
        </span>
        <span
          /* Почти вровень с основным словом, а не подстрочником. Мелкий
             суффикс читался как сноска; в паре «Vantage AI» это одно имя,
             и обе части должны стоять на одной высоте. Чуть меньший кегль
             оставлен намеренно: заглавные буквы при равном кегле выглядят
             крупнее строчных и перетягивают на себя. */
          className="font-display font-semibold uppercase leading-none text-violet-lit"
          style={{ fontSize: size * 0.74, letterSpacing: '0.03em' }}
        >
          AI
        </span>
      </span>
    </span>
  );
}
